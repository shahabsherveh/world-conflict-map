#!/usr/bin/env bash
# Regenerate requirements.lock from requirements.txt.
#
# Run this after editing requirements.txt (or accepting a Dependabot bump) and
# commit the lock with the change. Nothing else reads requirements.txt: the
# Dockerfile and CI both install the lock, which is what makes the image and the
# gates resolve the same versions on different days.
#
# Why a wrapper instead of a raw `uv pip compile` invocation: the torch CPU wheel
# only exists on PyTorch's index, so the extra index and the resolution strategy
# have to be identical every time (a plain compile would eventually pick a CUDA
# wheel from PyPI), and the generated file must carry that index URL so a caller
# needs no special-case flags. `--generate-hashes` then makes the install
# verifiable: pip refuses a wheel whose hash is not in the lock.
set -euo pipefail
cd "$(dirname "$0")/.."

TORCH_INDEX="https://download.pytorch.org/whl/cpu"
LOCK="requirements.lock"

check=0
case "${1:-}" in
  --check) check=1 ;;
  -h | --help)
    cat <<'EOF'
Regenerate requirements.lock from requirements.txt.

Usage: scripts/lock-deps.sh [--check]

  --check   print a diff and exit non-zero if the lock is stale
            (needs network; run it when reviewing a dependency bump, not
            as a per-commit gate: a new upstream release would otherwise
            redden an untouched commit)
EOF
    exit 0
    ;;
  "") ;;
  *)
    printf '[lock] unknown option: %s (try --help)\n' "$1" >&2
    exit 2
    ;;
esac

uv_bin="${UV_BIN:-$(command -v uv || true)}"
[ -n "$uv_bin" ] || {
  printf '[lock] uv not found; install it (https://docs.astral.sh/uv/) or set UV_BIN\n' >&2
  exit 1
}

tmp="$(mktemp)"
trap 'rm -f "$tmp" "$tmp.hashed"' EXIT
"$uv_bin" pip compile requirements.txt \
  --python-version 3.12 \
  --extra-index-url "$TORCH_INDEX" \
  --index-strategy unsafe-best-match \
  --generate-hashes \
  --no-header \
  --output-file "$tmp.hashed" >/dev/null

{
  cat <<'EOF'
# Generated by `scripts/lock-deps.sh` from requirements.txt — do not edit by hand.
#
# Installed by the Dockerfile and by CI, and audited by `pip-audit`. Hashes are
# included, so pip rejects a wheel that the lock was not built against.
#
# The extra index is here, not on the command line, so every caller resolves the
# CPU-only torch wheel without remembering a flag. torch's `+cpu` version does
# not exist on PyPI (see the note in docs/ci-cd.md about pip-audit skipping it).
--extra-index-url https://download.pytorch.org/whl/cpu

EOF
  cat "$tmp.hashed"
} > "$tmp"

if [ "$check" -eq 1 ]; then
  if diff -u "$LOCK" "$tmp"; then
    printf '[lock] %s is up to date\n' "$LOCK"
  else
    printf '[lock] %s is stale; re-run scripts/lock-deps.sh and commit it\n' "$LOCK" >&2
    exit 1
  fi
else
  mv "$tmp" "$LOCK"
  printf '[lock] wrote %s (%s lines)\n' "$LOCK" "$(wc -l < "$LOCK")"
fi
